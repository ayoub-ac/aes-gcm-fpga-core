"""Generate random AES-128-GCM test vectors for the C++ harness.

Output: a C++ header (random_vectors.h) defining a static table of
{key, iv, aad, plaintext, ciphertext, tag} tuples. The harness in
sim_main.cpp includes this header and runs each vector through the
DUT, comparing against the reference computed by Python's
`cryptography.hazmat.primitives.ciphers.aead.AESGCM`.

Strategy:
  * 100 random vectors, lengths drawn from:
      - tail of [0..15]  (single-block boundary, partial-last cases)
      - 16..31           (just past one block)
      - 32..256          (multi-block, larger AEAD payloads)
  * AAD length: 0, 12, 20, and small random in [0..32]
  * Each vector: encrypt -> store ciphertext + tag

Run: `python3 tb/gen_random_vectors.py > tb/random_vectors.h`
(invoked by `make regen_vectors`). Deterministic given the seed.
"""

import random
import sys

from cryptography.hazmat.primitives.ciphers.aead import AESGCM


def main() -> int:
    random.seed(0xA1E50C42)

    n_total = 100
    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later OR Commercial\n")
    out.write("// AUTO-GENERATED by tb/gen_random_vectors.py.\n"
              "// Do not edit by hand; regenerate with `make regen_vectors`.\n")
    out.write("#pragma once\n")
    out.write("#include <cstdint>\n")
    out.write("#include <cstddef>\n\n")
    out.write("struct AeadVec {\n")
    out.write("    const uint8_t* key;     // 16 bytes (AES-128)\n")
    out.write("    const uint8_t* iv;      // 12 bytes (96-bit IV)\n")
    out.write("    const uint8_t* aad;     // aad_len bytes\n")
    out.write("    size_t         aad_len;\n")
    out.write("    const uint8_t* pt;      // pt_len bytes\n")
    out.write("    size_t         pt_len;\n")
    out.write("    const uint8_t* ct;      // pt_len bytes\n")
    out.write("    const uint8_t* tag;     // 16 bytes\n")
    out.write("};\n\n")

    arena = bytearray()
    pos_table = []  # parallel: list of (offsets[6], aad_len, pt_len)

    for i in range(n_total):
        key = bytes(random.randint(0, 255) for _ in range(16))
        iv = bytes(random.randint(0, 255) for _ in range(12))

        # AAD: mix of 0, 12 (canonical), 20, small random
        choice = i % 4
        if choice == 0:
            aad_len = 0
        elif choice == 1:
            aad_len = 12
        elif choice == 2:
            aad_len = 20
        else:
            aad_len = random.randint(1, 32)
        aad = bytes(random.randint(0, 255) for _ in range(aad_len))

        # PT length: edge cases + random
        if i < 8:
            pt_len = i  # 0..7
        elif i < 16:
            pt_len = 8 + (i - 8)  # 8..15 (single-block partial-last)
        elif i < 24:
            pt_len = 16 + (i - 16)  # 16..23 (one full + 0..7)
        elif i < 32:
            pt_len = 32 + (i - 32 + 8)  # 32..39 (two full + 0..7)
        else:
            pt_len = random.randint(0, 256)
        pt = bytes(random.randint(0, 255) for _ in range(pt_len))

        gcm = AESGCM(key)
        ct_and_tag = gcm.encrypt(iv, pt, aad if aad_len > 0 else None)
        ct, tag = ct_and_tag[:-16], ct_and_tag[-16:]
        assert len(ct) == pt_len
        assert len(tag) == 16

        offs = []
        for blob in (key, iv, aad, pt, ct, tag):
            offs.append(len(arena))
            arena.extend(blob)
        pos_table.append((offs, aad_len, pt_len))

    arena.append(0)  # sentinel so &arena[N] is always valid

    out.write("static const uint8_t kAeadArena[] = {\n")
    for i in range(0, len(arena), 16):
        chunk = arena[i:i + 16]
        out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n\n")

    out.write("static const AeadVec kAeadVectors[] = {\n")
    for offs, aad_len, pt_len in pos_table:
        key_off, iv_off, aad_off, pt_off, ct_off, tag_off = offs
        out.write(f"    {{ kAeadArena + {key_off}, kAeadArena + {iv_off}, "
                  f"kAeadArena + {aad_off}, {aad_len}u, "
                  f"kAeadArena + {pt_off}, {pt_len}u, "
                  f"kAeadArena + {ct_off}, kAeadArena + {tag_off} }},\n")
    out.write("};\n\n")
    out.write("static constexpr size_t kAeadVectorCount ="
              " sizeof(kAeadVectors) / sizeof(kAeadVectors[0]);\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
